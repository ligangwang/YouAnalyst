import test from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {Firestore} from 'firebase-admin/firestore';
import {CompanyView} from '../../src/lib/market-store/company-view';
import {RetainedStore,RETAINED_CONTROL} from '../../src/lib/market-store/retained-store';
const host=process.env.FIRESTORE_EMULATOR_HOST;
if(host&&!/^(127\.0\.0\.1|localhost):\d+$/.test(host))throw Error('Local emulator required');
const check=host?test:test.skip;
check('company view shares reads, follows atomic root moves and deletions, and excludes other data',async t=>{
    const raw=new Firestore({projectId:'company-view-'+randomUUID()});
    let changes=0;
    const view=new CompanyView(raw,()=>{changes++;});
    t.after(async()=>{view.close();await raw.terminate();});
    const state=raw.doc('market_state/companies/records/US:A'),ugc=raw.doc('market_ugc/companies/records/US:A');
    await state.set({pending:true});
    await raw.doc('market_state/company_fundamentals/records/US:A').set({wrong:true});
    await raw.doc('market_state/companies-other/records/US:A').set({wrong:true});
    await raw.doc('market_ugc/companies/records/中文').set({name:'中文'});
    assert.equal(await view.read(),undefined,'point lookups alone must not bootstrap the full view');
    const warming=view.read(true);
    assert.equal(await view.read(),undefined,'point reads must not wait for an in-flight collection bootstrap');
    assert.deepEqual([...(await warming)!.keys()].sort(),['US:A','中文']);
    const initial=changes;
    for(let n=0;n<10;n++)assert.equal((await view.read())!.get('US:A')!.get('pending'),true);
    assert.equal(changes,initial,'repeated reads reuse the same subscription');
    const wait=async(predicate:()=>Promise<boolean>)=>{for(let n=0;n<100;n++){if(await predicate())return;await new Promise(r=>setTimeout(r,20));}assert.fail('snapshot did not catch up');};
    await raw.batch().delete(state).set(ugc,{name:'Reviewed',reviewedBy:'user'}).commit();
    await wait(async()=>(await view.read())?.get('US:A')?.get('name')==='Reviewed');
    assert.equal((await view.read())!.size,2);
    await ugc.delete();await wait(async()=>!(await view.read())!.has('US:A'));
    const bounded=new CompanyView(raw,()=>{},1);t.after(()=>bounded.close());
    assert.equal(await bounded.read(true),undefined,'oversized snapshots fall back, never return a partial collection');
});
check('retained view never replaces transactional authority',async t=>{
    const raw=new Firestore({projectId:'company-authority-'+randomUUID()});
    const prior=process.env.K_SERVICE;process.env.K_SERVICE='ifindata-web';
    const store=new RetainedStore(raw,false,()=>{});
    if(prior===undefined)delete process.env.K_SERVICE;else process.env.K_SERVICE=prior;
    t.after(async()=>{store.close();await raw.terminate();});
    await raw.doc(RETAINED_CONTROL).set({version:1,ready:true,cleanupAuthorized:true});
    const source=raw.doc('companies/US:A'),physical=raw.doc('market_state/companies/records/US:A');
    await physical.set({pending:true});
    await store.companies(undefined,true);
    assert.equal((await store.documents([source]))[0].ref.path,source.path);
    await raw.runTransaction(async tx=>{
        const context={reader:{get:(ref:FirebaseFirestore.DocumentReference|FirebaseFirestore.Query)=>tx.get(ref as FirebaseFirestore.DocumentReference),getAll:(...refs:FirebaseFirestore.DocumentReference[])=>tx.getAll(...refs)}};
        assert.equal(await store.companies(context,true),undefined);
        assert.equal((await store.documents([source],context))[0].get('pending'),true);
    });
});
